/* Runs real file:// editing, picking, persistence and portable configuration flows. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.ERP_PLAYWRIGHT_MODULE||'playwright');
const root=path.resolve(__dirname,'../../..');
const entry=pathToFileURL(path.join(root,'原型/预算管理/预算优化/prototype/index.html')).href+'#overview';
(async()=>{
  const browser=await chromium.launch({channel:process.env.ERP_BROWSER_CHANNEL||'chrome',headless:true});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
    const page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const bar=page.locator('erp-iteration-marks');
    const editor=bar.getByRole('dialog',{name:'配置版本标记',exact:true});
    await page.goto(entry);
    await bar.getByRole('button',{name:'配置标记',exact:true}).click({timeout:3000});
    const output=path.join(root,'文档/迭代/预算优化/版本标记验收');
    fs.mkdirSync(output,{recursive:true});
    await page.screenshot({path:path.join(output,'可视化配置面板.png')});
    await page.setViewportSize({width:1024,height:768});
    await editor.getByRole('button',{name:'保存标记',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,'可视化配置面板_1024.png')});
    assert.equal(await editor.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
    await page.setViewportSize({width:1440,height:1000});
    await editor.getByRole('button',{name:'新增标记',exact:true}).click();
    await editor.getByLabel('标记标题',{exact:true}).fill('测试：预算执行入口');
    await editor.getByLabel('变更说明',{exact:true}).fill('可视化选择区域，业务按钮不应被执行。');
    await editor.getByRole('button',{name:'选择页面区域',exact:true}).click();
    await page.locator('.legacy-ops [data-page="execute"]').first().click();
    assert.equal(await page.locator('#content').getAttribute('data-erp-page'),'overview');
    const picked=await page.evaluate(()=>document.querySelector('erp-iteration-marks').editor.candidate.outerHTML);
    await bar.getByRole('button',{name:'上一级区域',exact:true}).click();
    assert.notEqual(await page.evaluate(()=>document.querySelector('erp-iteration-marks').editor.candidate.outerHTML),picked);
    await bar.getByRole('button',{name:'返回下一级',exact:true}).click();
    assert.equal(await page.evaluate(()=>document.querySelector('erp-iteration-marks').editor.candidate.outerHTML),picked);
    await bar.getByRole('button',{name:'使用此区域',exact:true}).click();
    assert.ok(await editor.getByLabel('区域选择器',{exact:true}).inputValue());
    await editor.getByRole('button',{name:'保存标记',exact:true}).click();
    await editor.getByRole('status').filter({hasText:'已保存到当前浏览器'}).waitFor();
    await editor.getByRole('button',{name:'关闭配置',exact:true}).click();
    await bar.getByRole('button',{name:'隐藏标记',exact:true}).waitFor();
    const custom=await page.evaluate(()=>document.querySelector('erp-iteration-marks').config.marks.find(m=>m.title==='测试：预算执行入口'));
    await bar.locator('.pin[data-mark="'+custom.id+'"]').click();
    await bar.locator('article[data-id="'+custom.id+'"].selected').waitFor();
    await bar.getByRole('button',{name:'关闭变更说明',exact:true}).click();
    await page.reload();
    await bar.locator('.pin[data-mark="'+custom.id+'"]').waitFor();
    console.log('PASS 可视化新增、点选不触发业务、保存即时显示与刷新保留');

    await bar.getByRole('button',{name:'配置标记',exact:true}).click();
    await editor.getByRole('button',{name:'编辑标记：测试：预算执行入口',exact:true}).click();
    await editor.getByLabel('标记标题',{exact:true}).fill('测试：已编辑入口');
    await editor.getByRole('button',{name:'保存标记',exact:true}).click();
    await editor.getByText('管理迭代',{exact:true}).click();
    await editor.getByRole('button',{name:'新增迭代',exact:true}).click();
    await editor.getByLabel('迭代编号',{exact:true}).fill('ERP-NEXT');
    await editor.getByLabel('迭代名称',{exact:true}).fill('下一次优化');
    await editor.getByRole('button',{name:'保存迭代',exact:true}).click();
    await editor.getByRole('button',{name:'新增标记',exact:true}).click();
    await editor.getByLabel('标记标题',{exact:true}).fill('仅规则说明');
    await editor.getByLabel('所属迭代',{exact:true}).selectOption('ERP-NEXT');
    await editor.getByRole('button',{name:'保存标记',exact:true}).click();
    assert.equal(await editor.getByLabel('区域选择器',{exact:true}).inputValue(),'');
    await editor.getByRole('button',{name:'删除迭代',exact:true}).click();
    await editor.getByRole('status').filter({hasText:'仍有关联标记'}).waitFor();
    const downloadPromise=page.waitForEvent('download');
    await editor.getByRole('button',{name:'导出 JSON',exact:true}).click();
    const download=await downloadPromise;
    const exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(exported.id,'budget-optimization');
    assert.equal(exported.marks.length,15);
    assert.ok(exported.marks.some(m=>m.title==='测试：已编辑入口'));
    assert.ok(exported.versions.some(v=>v.id==='ERP-NEXT'));
    const scriptPromise=page.waitForEvent('download');
    await editor.getByRole('button',{name:'导出配置脚本',exact:true}).click();
    const scriptDownload=await scriptPromise;
    const sandbox={window:{}};
    vm.runInNewContext(fs.readFileSync(await scriptDownload.path(),'utf8'),sandbox);
    assert.deepEqual(JSON.parse(JSON.stringify(sandbox.window.BudgetIterationMarks)),exported);
    console.log('PASS 编辑、迭代管理、关联保护与完整配置导出');

    page.once('dialog',dialog=>dialog.accept());
    await editor.getByRole('button',{name:'删除标记',exact:true}).click();
    assert.equal(await editor.getByRole('button',{name:'编辑标记：仅规则说明',exact:true}).count(),0);
    page.once('dialog',dialog=>dialog.accept());
    await editor.getByRole('button',{name:'删除迭代',exact:true}).click();
    assert.equal(await editor.getByLabel('所属迭代',{exact:true}).locator('option[value="ERP-NEXT"]').count(),0);
    const input=editor.locator('input[type="file"]');
    await input.setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{oops')});
    await editor.getByRole('status').filter({hasText:'导入失败'}).waitFor();
    assert.equal(await page.evaluate(()=>document.querySelector('erp-iteration-marks').config.marks.length),14);
    await input.setInputFiles({name:'wrong-module.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...exported,id:'another-module'}))});
    await editor.getByRole('status').filter({hasText:'不属于当前模块'}).waitFor();
    page.once('dialog',dialog=>dialog.accept());
    await input.setInputFiles({name:'marks.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
    await editor.getByRole('status').filter({hasText:'已导入'}).waitFor();
    assert.equal(await page.evaluate(()=>document.querySelector('erp-iteration-marks').config.marks.length),15);
    await editor.getByRole('button',{name:'编辑标记：测试：已编辑入口',exact:true}).click();
    await editor.getByRole('button',{name:'选择页面区域',exact:true}).click();
    await page.keyboard.press('Escape');
    await editor.waitFor();
    assert.equal(await page.locator('#content').getAttribute('data-erp-page'),'overview');
    page.once('dialog',dialog=>dialog.accept());
    await editor.getByRole('button',{name:'恢复项目配置',exact:true}).click();
    await editor.getByRole('status').filter({hasText:'已恢复项目配置'}).waitFor();
    assert.equal(await page.evaluate(()=>document.querySelector('erp-iteration-marks').config.marks.length),13);
    await editor.getByRole('button',{name:'关闭配置',exact:true}).click();
    await page.reload();
    assert.equal(await page.evaluate(()=>document.querySelector('erp-iteration-marks').config.marks.length),13);
    console.log('PASS 删除、导入校验与回读、取消区域选择、恢复项目配置');

    const denied=await browser.newContext();
    await denied.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('blocked','SecurityError');};});
    const deniedPage=await denied.newPage();
    await deniedPage.goto(entry);
    const deniedBar=deniedPage.locator('erp-iteration-marks'),deniedEditor=deniedBar.getByRole('dialog',{name:'配置版本标记',exact:true});
    await deniedBar.getByRole('button',{name:'配置标记',exact:true}).click();
    await deniedEditor.getByRole('button',{name:'新增标记',exact:true}).click();
    await deniedEditor.getByLabel('标记标题',{exact:true}).fill('仅本次预览');
    await deniedEditor.getByRole('button',{name:'保存标记',exact:true}).click();
    await deniedEditor.getByRole('status').filter({hasText:'仅应用于本次预览'}).waitFor();
    assert.equal(await deniedPage.evaluate(()=>document.querySelector('erp-iteration-marks').config.marks.length),14);
    await denied.close();
    await page.goto(pathToFileURL(path.join(root,'index.html')).href);
    const workspaceBar=page.locator('#erp-version-marks');
    await workspaceBar.getByRole('button',{name:'配置标记',exact:true}).click();
    await workspaceBar.getByRole('dialog',{name:'配置版本标记',exact:true}).waitFor();
    await page.screenshot({path:path.join(output,'工作台配置入口.png')});
    await workspaceBar.getByRole('button',{name:'关闭配置',exact:true}).click();
    assert.deepEqual(errors,[]);
    console.log('PASS 禁止本地存储时如实提示并允许本次预览');
    await context.close();
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
