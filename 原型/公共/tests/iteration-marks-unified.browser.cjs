const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.ERP_PLAYWRIGHT_MODULE||'playwright');
const root=path.resolve(__dirname,'../../..');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
    const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root,'index.html')).href);
    const bar=page.locator('#erp-version-marks'),budget=page.frameLocator('iframe[data-module="budget"]');
    await bar.getByRole('button',{name:'显示标记',exact:true}).waitFor({timeout:3000});
    assert.equal(await page.getByRole('button',{name:'配置菜单标记',exact:true}).count(),0);
    assert.equal(await budget.getByRole('button',{name:'配置标记',exact:true}).isVisible(),false);
    await bar.getByRole('button',{name:'显示标记',exact:true}).click();
    await bar.locator('.pin[data-mark="menu-application"]').waitFor();
    await budget.locator('.pin[data-mark="overview-execution"]').waitFor();
    await budget.locator('.pin[data-mark="overview-execution"]').click();
    await bar.locator('article[data-id="overview-execution"].selected').waitFor();
    assert.equal(await bar.locator('article').count(),16);
    await bar.getByRole('button',{name:'关闭变更说明',exact:true}).click();
    await bar.getByRole('button',{name:'隐藏标记',exact:true}).click();
    await budget.locator('.pin').first().waitFor({state:'detached'});
    assert.equal(await bar.locator('.pin').count(),0);
    console.log('PASS 唯一入口、统一显示开关、统一清单与跨框架编号说明');

    await bar.getByRole('button',{name:'配置标记',exact:true}).click();
    const editor=bar.getByRole('dialog',{name:'配置版本标记',exact:true});
    await editor.getByRole('button',{name:'新增标记',exact:true}).click();
    await editor.getByLabel('标记标题',{exact:true}).fill('统一入口：菜单');
    await editor.getByLabel('标记范围',{exact:true}).selectOption('menu');
    await editor.getByRole('button',{name:'选择页面区域',exact:true}).click();
    await page.locator('nav [data-group="budget"] > summary').click();
    assert.equal(await page.locator('nav [data-group="budget"]').getAttribute('open'),'');
    await bar.getByRole('button',{name:'使用此区域',exact:true}).click();
    await editor.getByRole('button',{name:'保存标记',exact:true}).click();
    await editor.getByRole('button',{name:'新增标记',exact:true}).click();
    await editor.getByLabel('标记标题',{exact:true}).fill('统一入口：页面');
    await editor.getByLabel('标记范围',{exact:true}).selectOption('page');
    await editor.getByRole('button',{name:'选择页面区域',exact:true}).click();
    await budget.getByRole('button',{name:'取消选择',exact:true}).waitFor();
    await page.keyboard.press('Escape');
    await editor.waitFor();
    assert.equal(await editor.getByLabel('区域选择器',{exact:true}).inputValue(),'');
    await editor.getByRole('button',{name:'选择页面区域',exact:true}).click();
    await budget.locator('.legacy-ops [data-page="execute"]').first().click();
    assert.equal(await budget.locator('#content').getAttribute('data-erp-page'),'overview');
    await budget.getByRole('button',{name:'使用此区域',exact:true}).click();
    await editor.waitFor();
    assert.ok(await editor.getByLabel('区域选择器',{exact:true}).inputValue());
    await editor.getByRole('button',{name:'保存标记',exact:true}).click();
    const downloadPromise=page.waitForEvent('download');
    await editor.getByRole('button',{name:'导出 JSON',exact:true}).click();
    const data=JSON.parse(fs.readFileSync(await (await downloadPromise).path(),'utf8'));
    assert.equal(data.marks.length,18);
    assert.ok(data.marks.some(m=>m.scope==='menu'&&m.title==='统一入口：菜单'));
    assert.ok(data.marks.some(m=>m.scope==='page'&&m.module==='budget'&&m.title==='统一入口：页面'));
    await editor.getByRole('button',{name:'关闭配置',exact:true}).click();
    await page.reload();
    await bar.getByRole('button',{name:'隐藏标记',exact:true}).waitFor();
    assert.equal(await bar.evaluate(h=>h.config.marks.length),18);
    console.log('PASS 同一配置面板维护菜单与页面、点选不触发业务、统一导出与刷新保留');

    await bar.getByRole('button',{name:'全部变更',exact:false}).click();
    await bar.locator('article[data-id="execution-annual"]').getByRole('button',{name:'前往页面',exact:true}).click();
    await budget.locator('.pin[data-mark="execution-annual"]').waitFor();
    await page.locator('nav [data-module="receipt"]').click();
    await page.locator('#erp-tabs button[data-tab-id="receipt:list"][aria-current="page"]').waitFor();
    await bar.getByRole('button',{name:'配置标记',exact:true}).waitFor();
    assert.equal(await page.frameLocator('iframe[data-module="receipt"]').locator('erp-iteration-marks').count(),0);
    await page.evaluate(()=>window.postMessage({protocol:'erp-iteration-marks-v1',type:'open',id:'historical-rebuild'},'*'));
    assert.equal(await bar.getByRole('dialog',{name:'版本变更说明'}).isVisible(),false);
    await page.locator('nav [data-module="budget"][data-page="overview"]').click();
    await bar.getByRole('button',{name:'配置标记',exact:true}).click();
    await editor.getByText('管理迭代',{exact:true}).click();
    await editor.getByRole('button',{name:'新增迭代',exact:true}).click();
    await editor.getByLabel('迭代编号',{exact:true}).fill('ERP-EMPTY');
    await editor.getByLabel('迭代名称',{exact:true}).fill('空迭代');
    await editor.getByRole('button',{name:'保存迭代',exact:true}).click();
    await editor.getByRole('button',{name:'关闭配置',exact:true}).click();
    await bar.getByLabel('筛选迭代版本').selectOption('ERP-EMPTY');
    await budget.locator('.pin').first().waitFor({state:'detached'});
    assert.equal(await bar.locator('.pin').count(),0);
    await bar.getByLabel('筛选迭代版本').selectOption('ERP-I003');
    await bar.locator('.pin[data-mark="menu-application"]').waitFor();
    await budget.locator('.pin[data-mark="overview-execution"]').waitFor();
    await bar.getByRole('button',{name:'配置标记',exact:true}).click();
    page.once('dialog',dialog=>dialog.accept());
    await editor.getByRole('button',{name:'恢复项目配置',exact:true}).click();
    assert.equal(await bar.evaluate(h=>h.config.marks.length),16);
    await editor.getByRole('button',{name:'关闭配置',exact:true}).click();
    fs.mkdirSync(path.join(root,'文档/迭代/预算优化/版本标记验收'),{recursive:true});
    await page.screenshot({path:path.join(root,'文档/迭代/预算优化/版本标记验收/统一版本标记入口.png')});
    await page.setViewportSize({width:1024,height:768});
    await page.screenshot({path:path.join(root,'文档/迭代/预算优化/版本标记验收/统一版本标记入口_1024.png')});
    assert.deepEqual(errors,[]);
    console.log('PASS 跨页定位、跨模块公共入口、版本筛选统一及消息来源校验');

    const migrated=await browser.newContext();
    await migrated.addInitScript(()=>{
      if(localStorage.getItem('test-legacy-seeded'))return;
      localStorage.setItem('erp-iteration-marks:budget-optimization:config',JSON.stringify({id:'budget-optimization',versions:[{id:'ERP-I003',label:'预算优化'}],marks:[{id:'old-page',version:'ERP-I003',type:'new',page:'overview',title:'已有页面配置',selector:'.legacy-top'}]}));
      localStorage.setItem('erp-iteration-marks:erp-navigation:config',JSON.stringify({id:'erp-navigation',versions:[{id:'ERP-I003',label:'预算优化'}],marks:[{id:'old-menu',version:'ERP-I003',type:'new',page:'navigation',title:'已有菜单配置',selector:'[data-group="budget"]>summary'}]}));
      localStorage.setItem('test-legacy-seeded','true');
    });
    const legacy=await migrated.newPage();await legacy.goto(pathToFileURL(path.join(root,'index.html')).href);
    assert.deepEqual(await legacy.locator('#erp-version-marks').evaluate(h=>h.config.marks.map(m=>m.id)),['old-page','old-menu']);
    await legacy.reload();
    assert.equal(await legacy.locator('#erp-version-marks').evaluate(h=>h.config.marks.length),2);
    await migrated.close();
    console.log('PASS 旧页面与菜单自定义配置自动合并，刷新不重复追加');
    const preferences=await browser.newContext();
    await preferences.addInitScript(()=>{
      if(localStorage.getItem('test-preferences-seeded'))return;
      localStorage.setItem('erp-iteration-marks:budget-optimization',JSON.stringify({enabled:true,version:'ERP-I003'}));
      localStorage.setItem('test-preferences-seeded','true');
    });
    const preferencePage=await preferences.newPage();
    await preferencePage.goto(pathToFileURL(path.join(root,'index.html')).href);
    const preferenceBar=preferencePage.locator('#erp-version-marks');
    await preferenceBar.getByRole('button',{name:'隐藏标记',exact:true}).click();
    assert.equal(await preferenceBar.evaluate(h=>localStorage.getItem(h.storageKey+':config')),null);
    await preferencePage.reload();
    await preferenceBar.getByRole('button',{name:'显示标记',exact:true}).waitFor({timeout:3000});
    await preferences.close();
    console.log('PASS 旧开关偏好只迁入一次，统一偏好刷新保留且不固化项目默认配置');
    await context.close();
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
